import type { Metadata } from "next";
import Link from "next/link";
import { EmptyState, Mono, PageHeader, Panel, Tag } from "@/components/ui/primitives";
import { requirePageContext } from "@/lib/auth/context";
import { prisma } from "@/lib/db";
import { formatUtc } from "@/lib/domain/time";
import { firstParam, type SearchParams } from "@/lib/page";
import { listReports } from "@/lib/services/reports";

export const metadata: Metadata = { title: "Incident reports" };

export default async function ReportsPage({ searchParams }: { searchParams: SearchParams }) {
  const ctx = await requirePageContext();
  const params = await searchParams;
  const incidentId = firstParam(params.incident);
  const from = firstParam(params.from);
  const to = firstParam(params.to);
  const [reports, incidents] = await Promise.all([
    listReports(ctx, { incidentId, from, to }),
    prisma.incident.findMany({ where: { organizationId: ctx.organizationId }, select: { id: true, caseNumber: true }, orderBy: { caseNumber: "asc" } }),
  ]);
  const filtered = !!(incidentId || from || to);

  return (
    <div className="ct-page">
      <PageHeader
        crumbs={[{ label: "Investigation" }, { label: "Reports" }]}
        eyebrow="Investigation / reporting"
        title="Incident reports"
        subtitle="Versioned investigation snapshots, ready for review and export."
      />
      <Panel flush>
        <form className="flex flex-wrap items-end gap-3 border-b border-line p-4" method="get">
          <div>
            <label htmlFor="r-incident" className="ct-field-label">
              Case
            </label>
            <select id="r-incident" name="incident" className="ct-field min-w-[180px]" defaultValue={incidentId ?? ""}>
              <option value="">All cases</option>
              {incidents.map((i) => (
                <option key={i.id} value={i.id}>
                  {i.caseNumber}
                </option>
              ))}
            </select>
          </div>
          <div>
            <label htmlFor="r-from" className="ct-field-label">
              Generated from (UTC)
            </label>
            <input id="r-from" name="from" type="date" className="ct-field" defaultValue={from ?? ""} />
          </div>
          <div>
            <label htmlFor="r-to" className="ct-field-label">
              Generated to (UTC)
            </label>
            <input id="r-to" name="to" type="date" className="ct-field" defaultValue={to ?? ""} />
          </div>
          <button type="submit" className="ct-btn">
            Apply filters
          </button>
          {filtered && (
            <Link prefetch={false} href="/reports" className="ct-btn" data-variant="ghost">
              Reset filters
            </Link>
          )}
          <span className="ml-auto text-[12px] text-fg-2">{reports.length} snapshots</span>
        </form>
        {reports.length === 0 ? (
          filtered ? (
            <EmptyState title="No results match these filters." />
          ) : (
            <EmptyState title="No report snapshots have been generated.">Open an investigation and use Generate report.</EmptyState>
          )
        ) : (
          <div className="ct-table-wrap">
            <table className="ct-table">
              <caption className="ct-sr-only">Report snapshots</caption>
              <thead>
                <tr>
                  <th scope="col">Case</th>
                  <th scope="col">Report title</th>
                  <th scope="col">Version</th>
                  <th scope="col">Generated (UTC)</th>
                  <th scope="col">Generated by</th>
                  <th scope="col">Source mode</th>
                  <th scope="col">
                    <span className="ct-sr-only">Action</span>
                  </th>
                </tr>
              </thead>
              <tbody>
                {reports.map((r) => (
                  <tr key={r.id}>
                    <td>
                      <Mono>{r.caseNumber}</Mono>
                    </td>
                    <td className="min-w-[260px]">{r.title}</td>
                    <td>v{r.version}</td>
                    <td>
                      <Mono className="whitespace-nowrap text-[12px]">{formatUtc(r.generatedAt)}</Mono>
                    </td>
                    <td className="text-fg-2">{r.generatedBy}</td>
                    <td>
                      <div className="flex flex-wrap gap-1">
                        {r.publicReports && <Tag tone="info">PUBLIC REPORT</Tag>}
                        {r.simulated && <Tag tone="warning">SIMULATED</Tag>}
                        {!r.publicReports && !r.simulated && <Tag>Organisation data</Tag>}
                      </div>
                    </td>
                    <td>
                      <Link prefetch={false} href={`/reports/${r.id}`} className="ct-btn" data-size="sm" data-variant="ghost">
                        View report
                      </Link>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Panel>
    </div>
  );
}
